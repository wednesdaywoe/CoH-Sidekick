#!/usr/bin/env node
/**
 * Emit the Postgres half of the identity-name rule FROM the TypeScript half —
 * SECURITY_AUDIT.md F83.
 *
 * **Why this exists rather than a hand-written plpgsql function.** F83's row
 * left one clause open: `seed_profile_on_signup` writes a provider-supplied
 * name at signup and never passes through `update-profile`, so it got F82's
 * sigil handling and none of the invisible-character classes. The row said why
 * nobody had written those in SQL: "a plpgsql re-implementation of the
 * TypeScript rule would be a second copy of it in a second language, which is
 * the drift F10 and F85 were both filed for." That objection is correct about
 * a copy and does not apply to a DERIVATION. A generated class cannot drift
 * from the thing it is generated from; it can only be stale, and staleness is
 * something a gate can see.
 *
 * **It is derived by probing the real function, not by translating its
 * regexes.** `author-name.ts` holds four character classes and a hand-written
 * prefix loop, and copying those literals across would be a translation — with
 * every translation's failure mode, including the two this file's own comments
 * record (`/^@+/` and `/^[@\s]+/`, both shipped, both bypassed). Instead every
 * code point is put THROUGH `normalizeIdentityName` and sorted by what came
 * back. So if someone rewrites the internals tomorrow, the SQL follows; and if
 * the rewrite changes behaviour, the regeneration gate says so rather than the
 * two halves quietly disagreeing.
 *
 * Run it: `node scripts/gen-identity-sql.mjs --write`
 * Check it: `node scripts/gen-identity-sql.mjs --check` (exit 1 on drift)
 *
 * **Both CLI forms need a Node that strips types**, because the import below is
 * a `.ts` file: Node 22.18+ or 23.6+ do it by default, older ones want
 * `--experimental-strip-types` and Node 20 cannot do it at all. That is a
 * developer-machine requirement and deliberately NOT how the drift gate runs —
 * `supabase/identity-sql-generated.test.ts` imports `check()` from this module
 * instead, so the gate runs under vitest, which transpiles the import itself.
 * The gate first shipped as `execFileSync('node', ['--experimental-strip-types',
 * ...])` and went red on CI the moment it reached one: CI pins Node 20, the flag
 * is not a flag there, and a guard that cannot run where it is meant to run is
 * not a guard. It passed locally on Node 24 the whole time.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';

const HERE = fileURLToPath(new URL('.', import.meta.url));
const SCHEMA = `${HERE}../supabase/schema.sql`;
const BEGIN = '-- >>> GENERATED by scripts/gen-identity-sql.mjs -- do not edit by hand';
const END = '-- <<< GENERATED';

// Importing this module must not print the SQL or touch schema.sql -- the guard
// imports it. `process.argv[1]` is the script node was asked to run; under
// vitest it is the test runner, so none of this fires.
const invokedDirectly = process.argv[1] !== undefined
  && import.meta.url === pathToFileURL(process.argv[1]).href;


const { normalizeIdentityName } = await import('../supabase/functions/_shared/author-name.ts');

const MAX = 0x10FFFF;
/** Lone surrogates are not text; a probe would be measuring the probe. */
const isSurrogate = (cp) => cp >= 0xd800 && cp <= 0xdfff;

/**
 * The character the probe wraps each code point in. U+4E00, a CJK ideograph,
 * chosen for the one property that matters here: Unicode defines no
 * precomposed form of it with anything, so step 1 of the rule (NFC) cannot
 * fuse the probe with the thing being probed.
 *
 * **It was `a` for one run, and that was wrong.** `a` + U+0301 COMBINING ACUTE
 * composes to `\u00E1`, so all 1,134 combining marks came back as a string the
 * three buckets could not describe — every one of them looking like a rule
 * that mangles combining marks, when what was mangling them was the probe.
 * Caught because an unclassifiable code point exits non-zero here rather than
 * being dropped from the emitted class, which is the difference between a
 * generator that fails and one that silently emits a narrower rule than the
 * TypeScript it claims to mirror.
 */
const BASE = '\u4E00';

/**
 * Sort every code point by what the real rule does to it.
 *
 * `removed` and `spaced` are probed in the MIDDLE of a string, because that is
 * the only position where the difference between "vanishes" and "becomes a
 * gap" is observable — and that difference is the one `author-name.ts` says it
 * got wrong first time, welding `Savant\n\nAdministrator` into one word.
 *
 * `leading` is probed at the FRONT, and is deliberately a superset: it catches
 * the sigil, the blank openers, and anything already in the two sets above.
 * That costs nothing, because by the time the SQL strips a prefix the other
 * two have already run, and it means the class is defined by one question
 * ("would the rule drop this from the front?") rather than by an assembly of
 * three.
 */
function classify() {
  const removed = [], spaced = [], leading = [], surprising = [];
  for (let cp = 0; cp <= MAX; cp += 1) {
    if (isSurrogate(cp)) continue;
    const c = String.fromCodePoint(cp);
    // A code point NFC maps somewhere else cannot survive step 1, so it needs
    // no entry in any class here — its image is classified on its own pass.
    // U+0340 COMBINING GRAVE TONE MARK is the example: NFC sends it to U+0300,
    // and for one run all 1,118 such points looked like a rule that mangles
    // them. The SQL's own `normalize(raw, NFC)` does exactly this, first,
    // which is why skipping them is faithful rather than a gap.
    if (c.normalize('NFC') !== c) continue;
    const middle = normalizeIdentityName(`${BASE}${c}${BASE}`);
    if (middle === `${BASE}${BASE}`) removed.push(cp);
    else if (middle === `${BASE} ${BASE}`) spaced.push(cp);
    else if (middle !== `${BASE}${c}${BASE}`) surprising.push([cp, middle]);
    if (normalizeIdentityName(`${c}${BASE}`) === BASE) leading.push(cp);
  }
  return { removed, spaced, leading, surprising };
}

/** Collapse a sorted code-point list into [start, end] ranges. */
function toRanges(points) {
  const ranges = [];
  for (const cp of points) {
    const last = ranges[ranges.length - 1];
    // Surrogates are skipped above, so two points either side of the gap are
    // not adjacent in the list but ARE adjacent in any bracket expression that
    // spans them. Bridging the gap keeps the emitted class smaller and cannot
    // change what it matches, because nothing valid lives in it.
    if (last && (cp === last[1] + 1 || (last[1] === 0xd7ff && cp === 0xe000))) last[1] = cp;
    else ranges.push([cp, cp]);
  }
  return ranges;
}

/** One code point, as a Postgres regex character-entry escape. */
function esc(cp) {
  return cp <= 0xffff
    ? `\\u${cp.toString(16).padStart(4, '0').toUpperCase()}`
    : `\\U${cp.toString(16).padStart(8, '0').toUpperCase()}`;
}

/** A bracket expression's INNARDS — the caller decides `[...]` or `[^...]`. */
function bracket(ranges) {
  return ranges.map(([a, b]) => (a === b ? esc(a) : `${esc(a)}-${esc(b)}`)).join('');
}

const { removed, spaced, leading, surprising } = classify();
if (surprising.length) {
  // Not a warning. A code point the three buckets cannot describe means the
  // rule does something this generator does not model, and emitting SQL that
  // silently ignores it is how the two halves start disagreeing.
  console.error(`${surprising.length} code points fit none of the three buckets, e.g.`);
  for (const [cp, got] of surprising.slice(0, 10)) console.error(`  U+${cp.toString(16)} -> ${JSON.stringify(got)}`);
  process.exit(2);
}

const R = { removed: toRanges(removed), spaced: toRanges(spaced), leading: toRanges(leading) };
const counts = Object.fromEntries(Object.entries(R).map(([k, v]) => [k, v.length]));

const sql = `${BEGIN}
--
-- Derived from \`supabase/functions/_shared/author-name.ts\` by putting all
-- ${MAX + 1} code points through \`normalizeIdentityName\` and sorting them by
-- what came back. Regenerate with \`node scripts/gen-identity-sql.mjs --write\`;
-- \`supabase/identity-sql-generated.test.ts\` fails if this block and that file
-- have drifted apart.
--
-- ${counts.removed} ranges removed outright, ${counts.spaced} collapsed to a space,
-- ${counts.leading} strippable from the front of a name.
CREATE OR REPLACE FUNCTION identity_name_normalized(raw TEXT)
RETURNS TEXT AS $identity$
  SELECT btrim(
    -- 4. Whatever may not open a name comes off the front: the @ sigil, the
    --    blank openers, in any order and any number. The positive-class
    --    reasoning behind the set is in author-name.ts's OPENER comment; here
    --    it is just the answer.
    regexp_replace(
      -- 3. Collapse the runs the step below produced, then the outer btrim.
      regexp_replace(
        -- 2. The gaps become one space; the widthless ones vanish. Both in one
        --    pass each, and the order between them does not matter because a
        --    removed character cannot be what keeps two spaces apart once the
        --    collapse in step 3 runs after both.
        regexp_replace(
          regexp_replace(
            -- 1. NFC first, so nothing downstream measures a decomposed name.
            normalize(COALESCE(raw, ''), NFC),
            '[${bracket(R.removed)}]', '', 'g'),
          '[${bracket(R.spaced)}]', ' ', 'g'),
        '[ ]+', ' ', 'g'),
      '^[${bracket(R.leading)} ]*', '')
  );
$identity$ LANGUAGE sql IMMUTABLE;
${END}`;

const current = readFileSync(SCHEMA, 'utf8');
const start = current.indexOf(BEGIN);
const stop = current.indexOf(END);
if (start < 0 || stop < 0) {
  // Distinct from drift, and it stays distinct: exit 2 says the markers are
  // gone, exit 1 says the block between them is stale. A `throw` when this
  // module is imported rather than run, because `process.exit` inside vitest
  // takes the whole runner down and reports nothing about why.
  const complaint = `schema.sql carries no generated block; add the ${BEGIN} / ${END} markers first`;
  if (invokedDirectly) { console.error(complaint); process.exit(2); }
  throw new Error(complaint);
}
const existing = current.slice(start, stop + END.length);

/**
 * The single definition of "in sync". `--check` and the vitest guard both call
 * this, so there is one answer and not two that can disagree about what drift
 * means.
 */
export function check() {
  return { inSync: existing === sql, counts, generated: sql, committed: existing };
}

if (invokedDirectly) {
  if (process.argv.includes('--write')) {
    writeFileSync(SCHEMA, current.slice(0, start) + sql + current.slice(stop + END.length));
    console.log(`wrote ${sql.length} bytes: ${JSON.stringify(counts)}`);
  } else if (process.argv.includes('--check')) {
    if (check().inSync) console.log(`in sync: ${JSON.stringify(counts)}`);
    else { console.error('schema.sql has drifted from author-name.ts; run with --write'); process.exit(1); }
  } else {
    process.stdout.write(sql);
  }
}
